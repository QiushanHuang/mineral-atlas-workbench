assert.equal(E.preferences({audience:'teacher',loupe:true}).audience,'teacher');
assert.equal(E.keyboardAction({key:'Backspace',tagName:'CANVAS',active:true}),'back');
assert.equal(E.keyboardAction({key:'Enter',tagName:'TEXTAREA',active:true}),null);
assert.equal(E.keyboardAction({key:'Escape',tagName:'INPUT',active:true}),null);
assert.equal(E.keyboardAction({key:'Enter',tagName:'CANVAS',active:false}),null);
assert.equal(E.keyboardAction({key:'z',ctrlKey:true,tagName:'CANVAS',active:true}),'undo');
