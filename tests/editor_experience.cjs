const C=require('../ui/editor-canvas.js');
assert.equal(typeof C.labelLayout,'function','teaching labels remain whole and do not cover each other');
const input=[{text:'F02 reference (0 -1 0)',x:80,y:110,width:150,height:20},{text:'F03 reference (0 0 -1)',x:160,y:110,width:150,height:20}];
const placed=C.labelLayout(input,260,200);
assert.equal(placed.length,2);
assert.ok(placed.every(p=>p.left>=0&&p.right<=260&&p.top>=0&&p.bottom<=200));
const [a,b]=placed;
assert.ok(a.right<=b.left||b.right<=a.left||a.bottom<=b.top||b.bottom<=a.top);
assert.deepEqual(input.map(p=>p.y),[110,110]);
assert.equal(typeof E.photoFrame,'function','real-photo object focus keeps original pixel coordinates');
const full=E.photoFrame([960,1280],[402,360]);
const focused=E.photoFrame([960,1280],[402,360],[157,556,709,808]);
assert.ok(focused.s>full.s*2);
const pixel=[370,611],screen=[focused.x+pixel[0]*focused.s,focused.y+pixel[1]*focused.s];
assert.ok(screen[0]>0&&screen[0]<402&&screen[1]>0&&screen[1]<360);
assert.ok(Math.abs((screen[0]-focused.x)/focused.s-pixel[0])<1e-9);
