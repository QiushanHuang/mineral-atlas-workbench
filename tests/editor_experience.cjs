const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const file=path.join(__dirname,'../ui/editor-experience.js');
assert.ok(fs.existsSync(file),'guided experience exposes validated preferences and nonintrusive keyboard actions');
const E=require(file);
assert.equal(E.preferences({}).snap,true);
assert.equal(E.preferences({snap:false}).snap,false);
assert.equal(E.preferences({audience:'invalid',radius:NaN}).audience,'beginner');
